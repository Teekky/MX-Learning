const TAGS = ['aussie', 'aussie-construction']

function w(
  lemma: string,
  partOfSpeech: Word['partOfSpeech'],
  level: Word['level'],
  icon: LucideIcon,
  fr: string,
  definitionEn: string,
  exampleEn: string,
): AussieWordSeed {
  return {
    lemma,
    partOfSpeech,
    level,
    icon,
    tags: TAGS,
    fr,
    definitionEn,
    examples: [{ en: exampleEn }],
  }
}

