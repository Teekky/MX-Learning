/**
 * Curated idiom corpus.
 *
 * Idioms are the last thing a C1 learner picks up and the first thing that
 * marks them as fluent, because you cannot derive them — "let's take this
 * offline" has nothing to do with the internet. What matters as much as the
 * meaning is *where you can say it*: register (would this land in a design
 * review or only at the pub?) and regional variant (say "ballpark figure"
 * in London and half the room hears an Americanism).
 *
 * So every entry carries four things beyond the definition:
 *   register  informal | neutral | formal
 *   variant   BrE | AmE | both
 *   example   the expression doing its job in a real sentence
 *   literal   only where the surface reading actively misleads
 *
 * The corpus is embedded rather than fetched: it must work offline on the
 * phone, and it costs nothing to ship. Users extend it from inside the app
 * (words with `source: 'user'`), which is why nothing here is treated as
 * privileged — an app-added idiom is the same shape as a bundled one.
 */

import type { Word } from '@/types'

/** A bundled idiom: everything a Word needs except its per-install fields. */
export type IdiomSeed = Omit<Word, 'id' | 'addedAt' | 'source'>

/** Themes used by the browse filter. Kept short — these are chips, not prose. */
export const IDIOM_THEMES = [
  'meetings',
  'decisions',
  'deadlines',
  'people',
  'communication',
  'business',
  'effort',
  'outcomes',
  'everyday',
] as const

export type IdiomTheme = (typeof IDIOM_THEMES)[number]

/** Compact constructor — the table below would be unreadable otherwise. */
function idiom(
  lemma: string,
  level: Word['level'],
  register: NonNullable<Word['register']>,
  variant: NonNullable<Word['variant']>,
  theme: IdiomTheme,
  definitionEn: string,
  fr: string,
  exampleEn: string,
  literal?: string,
): IdiomSeed {
  return {
    lemma,
    partOfSpeech: 'idiom',
    level,
    register,
    variant,
    tags: ['idiom', theme],
    definitionEn,
    fr,
    examples: [{ en: exampleEn }],
    ...(literal ? { literal } : {}),
  }
}

