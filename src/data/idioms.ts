/** Every theme present in the corpus, in display order, with counts. */
export function idiomThemeCounts(): Array<{ theme: IdiomTheme; count: number }> {
  const counts = new Map<string, number>()
  for (const item of IDIOMS) {
    for (const tag of item.tags) {
      if (tag === 'idiom') continue
      counts.set(tag, (counts.get(tag) ?? 0) + 1)
    }
  }
  return IDIOM_THEMES.filter((t) => counts.has(t)).map((theme) => ({
    theme,
    count: counts.get(theme)!,
  }))
}
